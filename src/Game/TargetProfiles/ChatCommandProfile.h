    struct WireIdentity
    {
        int mPlayerId = -1;
        std::wstring mWireName;
        int mColor = -1;
    };
    struct PeerIdentity
    {
        int mId = -1;
        std::wstring mName;
    };
    inline int FindUniquePeer(const std::vector<PeerIdentity>& peers, std::wstring_view name)
    {
        int nameIndex = -1;
        for (std::size_t index = 0; index < peers.size(); ++index)
        {
            if (peers[index].mName == name) { if (nameIndex != -1) return -1; nameIndex = static_cast<int>(index); }
        }
        if (nameIndex < 0) return -1;
        const auto id = peers[static_cast<std::size_t>(nameIndex)].mId;
        if (id < 0) return -1;
        for (std::size_t index = 0; index < peers.size(); ++index)
            if (static_cast<int>(index) != nameIndex && peers[index].mId == id) return -1;
        return nameIndex;
    }
    inline bool IsNativeUnicastAddress(const std::array<std::uint8_t, 10>& address, int mode)
    {
        // 53EE00 的精确广播判据：模式1比较全部10字节，模式2比较末6字节；不猜测 sockaddr 布局。
        if (mode != 1 && mode != 2) return false;
        if (std::all_of(address.begin(), address.end(), [](auto value) { return value == 0; })) return false;
        return !std::all_of(address.begin() + (mode == 1 ? 0 : 4), address.end(), [](auto value) { return value == 0xFF; });
    }
    inline std::wstring EncodeWireName(std::wstring_view name)
    {
        std::wstring wire;
        for (const auto character : name)
        {
            const auto low = static_cast<unsigned char>(character & 0xFF);
            if (!low) break;
            wire += static_cast<wchar_t>(low);
        }
        return wire;
    }
    inline int ResolveWireIdentity(const std::vector<WireIdentity>& players, std::wstring_view name, int color, bool complete = true)
    {
        if (!complete) return -1;
        int found = -1;
        for (const auto& player : players)
        {
            if (player.mColor != color || player.mWireName != name) continue;
            if (found != -1) return -1;
            found = player.mPlayerId;
        }
        return found;
    }

