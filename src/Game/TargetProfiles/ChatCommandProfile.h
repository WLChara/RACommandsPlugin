    inline bool ConsumeOpeningSlashEcho(bool& pending, wchar_t character) noexcept
    {
        if (!pending) return false;
        pending = false;
        return character == L'/';
    }

    /** 回退输入提交前只接受完整、未溢出的原生正文范围；读取失败不发布部分字符串。 */
    template<typename TReader>
    bool ReadFallbackDraft(TReader&& reader, std::uintptr_t buffer, std::uint32_t initial,
        std::uint32_t current, bool overflowEnabled, wchar_t overflowFirst, std::wstring& output)
    {
        if (overflowEnabled || overflowFirst || initial > 64 || current < initial || current >= 162 || current - initial > 97) return false;
        std::wstring text;
        for (std::uint32_t index = initial; index <= current; ++index)
        {
            wchar_t character = 0;
            if (!reader(buffer + index * sizeof(wchar_t), &character, sizeof(character))) return false;
            if (index == current)
            {
                if (character) return false;
                output = std::move(text);
                return true;
            }
            if (!character) return false;
            text += character;
        }
        return false;
    }

    inline bool IsExclusiveRelayMask(const int* ids, const std::uint8_t* masks, std::size_t count, int playerId, int receiverAlias = -1)
    {
        if (!ids || !masks || !count || count > MAX_PLAYERS) return false;
        std::size_t matches = 0;
        std::uint8_t target = 0;
        for (std::size_t index = 0; index < count; ++index)
            if (ids[index] == playerId) { ++matches; target = masks[index]; }
        if (matches != 1 || !target || target == 0xFF || (target & (target - 1))) return false;
        for (std::size_t index = 0; index < count; ++index)
        {
            // 原生 Lookup 把0折为FF；其他接收者为0也不能视为不重叠。
            const auto effectiveMask = masks[index] ? masks[index] : std::uint8_t{0xFF};
            if (ids[index] != playerId && ids[index] != receiverAlias && (effectiveMask & target)) return false;
        }
        return true;
    }

    inline bool AreRelayReceiversExclusive(const int* ids, const std::uint8_t* masks, std::size_t count,
        int connectionId, int recipientHouseId, const std::vector<int>& receiverHouses)
    {
        if (!IsExclusiveRelayMask(ids, masks, count, connectionId, recipientHouseId)) return false;
        std::uint8_t selected = 0;
        for (std::size_t index = 0; index < count; ++index) if (ids[index] == connectionId) selected = masks[index];
        bool targetFound = false;
        for (const auto house : receiverHouses)
        {
            std::size_t matches = 0;
            std::uint8_t mask = 0;
            for (std::size_t index = 0; index < count; ++index)
                if (ids[index] == house) { ++matches; mask = masks[index]; }
            if (matches != 1 || !mask || mask == 0xFF) return false;
            if (house == recipientHouseId) { targetFound = true; if (mask != selected) return false; }
            else if (mask & selected) return false;
        }
        return targetFound;
    }

    /** 只对同步原生提交临时切换收件人；失败和异常均原样恢复八个标志及旧频道。 */
    template<typename TSend>
    bool WithSelectedRecipient(std::uint8_t* flags, std::uint32_t& route, int recipient, TSend&& send)
    {
        if (!flags || recipient < 0 || recipient >= static_cast<int>(MAX_PLAYERS)) return false;
        struct Restore
        {
            std::uint8_t* mFlags;
            std::uint32_t& mRoute;
            std::array<std::uint8_t, MAX_PLAYERS> mSavedFlags;
            std::uint32_t mSavedRoute;
            ~Restore() { std::copy(mSavedFlags.begin(), mSavedFlags.end(), mFlags); mRoute = mSavedRoute; }
        };
        Restore restore{ flags, route, {}, route };
        std::copy_n(flags, MAX_PLAYERS, restore.mSavedFlags.begin());
        std::fill_n(flags, MAX_PLAYERS, std::uint8_t{0});
        flags[recipient] = 1;
        route = 1;
        return std::forward<TSend>(send)();
    }

