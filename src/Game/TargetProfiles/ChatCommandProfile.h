    template<std::size_t TSize, typename TReader>
    bool MatchPath(TReader& reader, std::uintptr_t address, const std::array<std::uint8_t, TSize>& expected)
    {
        std::array<std::uint8_t, TSize> actual{};
        return reader(address, actual.data(), actual.size()) && actual == expected;
    }

    template<typename TReader>
    bool ValidatePrivatePath(TReader&& reader, bool relay)
    {
        return MatchPath(reader, RECIPIENT_DISPATCH_ADDRESS, RECIPIENT_DISPATCH_BYTES) &&
            MatchPath(reader, CONNECTION_ID_ADDRESS, CONNECTION_ID_BYTES) &&
            MatchPath(reader, CONNECTION_NAME_ADDRESS, CONNECTION_NAME_BYTES) &&
            MatchPath(reader, CONNECTION_ADDRESS_ADDRESS, CONNECTION_ADDRESS_BYTES) &&
            MatchPath(reader, SEND_WRAPPER_ADDRESS, SEND_WRAPPER_BYTES) &&
            (!relay || MatchPath(reader, FALLBACK_MASK_ADDRESS, FALLBACK_MASK_BYTES));
    }
